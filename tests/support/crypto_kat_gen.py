#!/usr/bin/env python3
"""Generate the crypto known-answer fixtures in tests/integration/v4/7.5-stdlib.

The vectors are copied from the official documents, not computed:

  NIST CAVP SHS byte vectors   shabytetestvectors.zip  (SHA-1, SHA-2)
  NIST CAVP SHA-3 byte vectors sha-3bytetestvectors.zip
  NIST CAVP GCM vectors        gcmtestvectors.zip      (AES-256, 96-bit IV, 128-bit tag)
  RFC 1321 (MD5), RFC 2202 (HMAC-MD5, HMAC-SHA-1), RFC 4231 (HMAC-SHA-2),
  RFC 4648 (base16/base64), RFC 5869 (HKDF), RFC 6070 (PBKDF2-HMAC-SHA1),
  RFC 7914 (PBKDF2-HMAC-SHA256, scrypt), RFC 8439 (ChaCha20-Poly1305)

usage: crypto_kat_gen.py <dir with the RFC .txt files and unzipped CAVP .rsp files>

Download:
  https://www.rfc-editor.org/rfc/rfcNNNN.txt
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/shs/shabytetestvectors.zip
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/sha3/sha-3bytetestvectors.zip
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/mac/gcmtestvectors.zip

The fixtures print one "<group>: passed/total" line per group and a FAIL line
for any mismatch, so the .expected files stay small.
"""
import os
import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
OUT = Path(__file__).resolve().parent.parent / "integration" / "v4" / "7.5-stdlib"


def find(name):
    for root, _dirs, files in os.walk(SRC):
        if name in files:
            return Path(root) / name
    raise SystemExit(f"missing {name} under {SRC}")


def text(name):
    return find(name).read_text(encoding="latin-1")


def lit(hexstr):
    """An Iron expression for bytes given as hex; long literals are split."""
    if hexstr == "":
        return '""'
    parts = [hexstr[i:i + 2000] for i in range(0, len(hexstr), 2000)]
    return "h(" + " + ".join(f'"{p}"' for p in parts) + ")"


class Group:
    def __init__(self, name):
        self.name = name
        self.lines = []

    def kat(self, label, expr, want_hex):
        self.lines.append(f'    ok += kat("{label}", {expr}, "{want_hex}")')
        self.lines.append("    total += 1")

    def check(self, label, cond):
        self.lines.append(f'    ok += check("{label}", {cond})')
        self.lines.append("    total += 1")

    def raw(self, line):
        self.lines.append("    " + line)

    def emit(self):
        fn = re.sub(r"[^a-z0-9]+", "_", self.name.lower()).strip("_")
        body = "\n".join(self.lines)
        return (f"func group_{fn}() {{\n    var ok = 0\n    var total = 0\n{body}\n"
                f'    println("{self.name}: {{ok}}/{{total}}")\n}}\n'), f"group_{fn}"


HEADER = """-- {title}
-- Generated by tests/support/crypto_kat_gen.py from {sources}.
-- Every expected value is copied from those documents.
import crypto
import encoding

func h(x: String) -> String {{
    val d = Hex.decode(x)
    assert(d.error == 0, "bad hex in fixture")
    return d.data
}}

func kat(label: String, got: String, want: String) -> Int {{
    val hex = Hex.encode(got)
    if hex == want {{
        return 1
    }}
    println("FAIL {{label}}: got {{hex}} want {{want}}")
    return 0
}}

func check(label: String, cond: Bool) -> Int {{
    if cond {{
        return 1
    }}
    println("FAIL {{label}}")
    return 0
}}
"""


def write(name, title, sources, groups):
    out = [HEADER.format(title=title, sources=sources)]
    calls = []
    expected = []
    for g in groups:
        src, fn = g.emit()
        out.append(src)
        calls.append(f"    {fn}()")
        n = sum(1 for l in g.lines if l.strip() == "total += 1")
        expected.append(f"{g.name}: {n}/{n}")
    out.append("func main() {\n" + "\n".join(calls) + "\n}\n")
    (OUT / f"{name}.iron").write_text("\n".join(out))
    (OUT / f"{name}.expected").write_text("\n".join(expected) + "\n")
    print(f"wrote {name}: " + ", ".join(expected))


# ── CAVP .rsp parsing ────────────────────────────────────────────────────

def rsp_records(name):
    recs, cur, hdr = [], {}, {}
    for line in text(name).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            if cur:
                recs.append(cur)
                cur = {}
            continue
        m = re.match(r"\[(\w+) = (\d+)\]", line)
        if m:
            hdr[m.group(1)] = int(m.group(2))
            continue
        if line == "FAIL":
            cur["FAIL"] = True
            continue
        if "=" in line:
            k, v = [s.strip() for s in line.split("=", 1)]
            if not cur:
                cur = {"_hdr": dict(hdr)}
            cur[k] = v
    if cur:
        recs.append(cur)
    return recs


def sha_group(label, alg, short, long_):
    g = Group(f"{label} NIST CAVP")
    recs = [r for r in rsp_records(short) if "Msg" in r]
    picks = [r for r in recs if int(r["Len"]) % 64 == 0 or int(r["Len"]) in (8, 24, 440, 448, 456)]
    picks = picks[:12]
    for r in picks:
        msg = "" if r["Len"] == "0" else r["Msg"].lower()
        g.kat(f"{label} ShortMsg Len={r['Len']}", f"Crypto.hash(HashAlgorithm.{alg}, {lit(msg)})", r["MD"].lower())
    longs = [r for r in rsp_records(long_) if "Msg" in r]
    longs.sort(key=lambda r: int(r["Len"]))
    for r in longs[:2]:
        g.kat(f"{label} LongMsg Len={r['Len']}", f"Crypto.hash(HashAlgorithm.{alg}, {lit(r['Msg'].lower())})", r["MD"].lower())
        # The same message through the streaming hasher, in uneven pieces.
        msg = r["Msg"].lower()
        g.raw("if true {")
        g.raw(f"    val m = {lit(msg)}")
        g.raw(f"    var hs = Hasher.new(HashAlgorithm.{alg})")
        g.raw("    var at = 0")
        g.raw("    var step = 1")
        g.raw("    while at < m.byte_len() {")
        g.raw("        hs.update(m.byte_slice(at, at + step))")
        g.raw("        at += step")
        g.raw("        step = step * 3 + 1")
        g.raw("    }")
        g.raw(f'    ok += kat("{label} LongMsg Len={r["Len"]} streamed", hs.finish(), "{r["MD"].lower()}")')
        g.raw("    total += 1")
        g.raw("}")
    return g


def gen_hash():
    groups = [
        sha_group("SHA-1", "Sha1", "SHA1ShortMsg.rsp", "SHA1LongMsg.rsp"),
        sha_group("SHA-224", "Sha224", "SHA224ShortMsg.rsp", "SHA224LongMsg.rsp"),
        sha_group("SHA-256", "Sha256", "SHA256ShortMsg.rsp", "SHA256LongMsg.rsp"),
        sha_group("SHA-384", "Sha384", "SHA384ShortMsg.rsp", "SHA384LongMsg.rsp"),
        sha_group("SHA-512", "Sha512", "SHA512ShortMsg.rsp", "SHA512LongMsg.rsp"),
        sha_group("SHA3-256", "Sha3_256", "SHA3_256ShortMsg.rsp", "SHA3_256LongMsg.rsp"),
        sha_group("SHA3-512", "Sha3_512", "SHA3_512ShortMsg.rsp", "SHA3_512LongMsg.rsp"),
    ]
    # The shortcut functions agree with Crypto.hash, and the hasher can be
    # reused after finish.
    g = Group("shortcuts and streaming")
    for fn, alg in [("sha1", "Sha1"), ("sha224", "Sha224"), ("sha256", "Sha256"), ("sha384", "Sha384"),
                    ("sha512", "Sha512"), ("sha3_256", "Sha3_256"), ("sha3_512", "Sha3_512"), ("md5", "Md5")]:
        g.check(f"Crypto.{fn} matches Crypto.hash",
                f'Crypto.{fn}("iron") == Crypto.hash(HashAlgorithm.{alg}, "iron") and '
                f'Crypto.{fn}("iron").byte_len() == Crypto.hash_size(HashAlgorithm.{alg})')
    g.raw("var hr = Hasher.new(HashAlgorithm.Sha256)")
    g.raw('hr.update("first message")')
    g.raw("val first = hr.finish()")
    g.raw('hr.update("second")')
    g.raw('ok += check("hasher restarts after finish", hr.finish() == Crypto.sha256("second") and first == Crypto.sha256("first message"))')
    g.raw("total += 1")
    g.raw("var big = Hasher.new(HashAlgorithm.Sha256)")
    g.raw('val thousand = "a".repeat(1000)')
    g.raw("for i in range(1000) {")
    g.raw("    big.update(thousand)")
    g.raw("}")
    # FIPS 180-2 appendix B.3: one million repetitions of "a".
    g.raw('ok += kat("SHA-256 one million a (FIPS 180-2 B.3)", big.finish(), "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0")')
    g.raw("total += 1")
    groups.append(g)

    m = Group("MD5 RFC 1321")
    t = text("rfc1321.txt")
    body = t[t.index('MD5 ("") ='):]
    body = re.sub(r"\n\s*", "", body[:body.index("\n\n")])  # undo the line wraps
    for msg, digest in re.findall(r'MD5 \("([^"]*)"\) =\s*([0-9a-f]{32})', body):
        m.kat(f'MD5 len={len(msg)}', f"Crypto.md5({lit(msg.encode().hex())})", digest)
    groups.append(m)
    write("crypto_hash_kat", "Hash known-answer tests: NIST CAVP SHA-1, SHA-2, SHA-3; RFC 1321 MD5.",
          "NIST CAVP SHS/SHA-3 byte vectors and RFC 1321", groups)


# ── HMAC, HKDF, PBKDF2, scrypt ───────────────────────────────────────────

def rfc4231():
    t = text("rfc4231.txt")
    g = Group("HMAC-SHA-2 RFC 4231")
    cases = re.split(r"\n4\.(\d+)\.  Test Case (\d+)", t)
    for i in range(1, len(cases), 3):
        n = cases[i + 1]
        block = cases[i + 2].split("\n5.  Security")[0]
        fields, cur = {}, None
        for line in block.splitlines():
            m = re.match(r"^   (Key|Data|HMAC-SHA-\d+)\s*=?\s+([0-9a-f]+)", line)
            if m:
                cur = m.group(1)
                fields[cur] = m.group(2)
                continue
            m = re.match(r"^\s{18}([0-9a-f]+)", line)
            if m and cur:
                fields[cur] += m.group(1)
                continue
            if line.strip() == "" or line.startswith("RFC") or "[Page" in line:
                continue
            if not re.match(r"^\s{18}", line):
                cur = None if not line.startswith("   HMAC") else cur
        trunc = n == "5"
        for alg, bits in [("Sha224", "224"), ("Sha256", "256"), ("Sha384", "384"), ("Sha512", "512")]:
            want = fields[f"HMAC-SHA-{bits}"]
            expr = f"Crypto.hmac(HashAlgorithm.{alg}, {lit(fields['Key'])}, {lit(fields['Data'])})"
            if trunc:
                expr += ".byte_slice(0, 16)"
            g.kat(f"RFC 4231 case {n} HMAC-SHA-{bits}", expr, want)
    return g


def rfc2202():
    t = text("rfc2202.txt")
    g = Group("HMAC-MD5 and HMAC-SHA-1 RFC 2202")

    def value(v):
        v = v.strip()
        m = re.match(r"0x([0-9a-f]{2}) repeated (\d+) times", v)
        if m:
            return m.group(1) * int(m.group(2))
        if v.startswith("0x"):
            return v[2:]
        return v.strip('"').encode().hex()

    for section, alg in [("2. Test Cases for HMAC-MD5", "Md5"), ("3. Test Cases for HMAC-SHA-1", "Sha1")]:
        s = t[t.index(section):]
        s = s[:s.index("\n3. Test Cases") if alg == "Md5" else s.index("\n4. Security")]
        s = re.sub(r"\n\nCheng & Glenn.*?\n\nRFC 2202[^\n]*\n", "\n", s, flags=re.S)
        s = re.sub(r'(Larger)\n\s+(Than)', r"\1 \2", s)
        seen = set()
        for case in re.split(r"\ntest_case =\s+", s)[1:]:
            n = case.split("\n", 1)[0].strip()
            if n in seen:
                continue  # the RFC prints SHA-1 cases 6 and 7 twice
            seen.add(n)
            f = {}
            for line in case.splitlines():
                m = re.match(r"^(key|data|digest|digest-96)\s*=?\s+(.*)$", line)
                if m and m.group(1) not in f:  # a stray digest line follows SHA-1 case 7
                    f[m.group(1)] = m.group(2)
            expr = f"Crypto.hmac(HashAlgorithm.{alg}, {lit(value(f['key']))}, {lit(value(f['data']))})"
            g.kat(f"RFC 2202 HMAC-{alg.upper()} case {n}", expr, value(f["digest"]))
    return g


def rfc5869():
    t = text("rfc5869.txt")
    g = Group("HKDF RFC 5869")
    t = re.sub(r"\n\n+[A-Z][a-z]+ & [A-Z][a-z]+ +Informational +\[Page \d+\]\n\x0c?\nRFC 5869[^\n]*\n", "\n", t)
    for n in range(1, 8):
        s = t[t.index(f"A.{n}.  Test Case {n}"):]
        s = s[:s.index(f"A.{n + 1}.") if n < 7 else s.index("Authors' Addresses")]
        f, cur = {}, None
        for line in s.splitlines():
            m = re.match(r"^   (Hash|IKM|salt|info|L|PRK|OKM)\s*=\s*(.*)$", line)
            if m:
                cur = m.group(1)
                f[cur] = m.group(2)
                continue
            m = re.match(r"^\s{10}([0-9a-f]+)", line)
            if m and cur:
                f[cur] += " " + m.group(1)

        def hx(v):
            v = re.sub(r"\(\d+ octets\)", "", v).strip()
            if v.startswith("not provided") or v == "":
                return ""
            return v.replace("0x", "").replace(" ", "")

        alg = {"SHA-256": "Sha256", "SHA-1": "Sha1"}[f["Hash"].strip()]
        expr = (f"Crypto.hkdf(HashAlgorithm.{alg}, {lit(hx(f['IKM']))}, {lit(hx(f['salt']))}, "
                f"{lit(hx(f['info']))}, {int(f['L'].strip())}).data")
        g.kat(f"RFC 5869 case {n}", expr, hx(f["OKM"]))
    return g


def rfc6070():
    t = text("rfc6070.txt")
    g = Group("PBKDF2-HMAC-SHA1 RFC 6070")
    for m in re.finditer(r'P = "([^"]*)".*?S = "([^"]*)".*?c = (\d+)\s+dkLen = (\d+).*?DK = (.*?)\(\d+ octets\)', t, re.S):
        p, s, c, dk_len, dk = m.groups()
        if int(c) > 100000:
            continue  # 16777216 iterations: minutes of CPU for no extra coverage
        p = p.replace("\\0", "\0")
        s = s.replace("\\0", "\0")
        want = re.sub(r"[^0-9a-f]", "", dk)
        g.kat(f"RFC 6070 c={c} dkLen={dk_len} P={len(p)} octets",
              f"Crypto.pbkdf2(HashAlgorithm.Sha1, {lit(p.encode().hex())}, {lit(s.encode().hex())}, {c}, {dk_len}).data",
              want)
    return g


def rfc7914():
    t = text("rfc7914.txt")
    g = Group("PBKDF2-HMAC-SHA256 and scrypt RFC 7914")
    t = re.sub(r"\n\n+Percival & Josefsson[^\n]*\n\x0c?\nRFC 7914[^\n]*\n", "\n", t)
    for m in re.finditer(r'PBKDF2-HMAC-SHA-256 \(P="([^"]*)", S="([^"]*)",\s+c=(\d+), dkLen=(\d+)\) =\n((?:\s+(?:[0-9a-f]{2} ?)+\n)+)', t):
        p, s, c, dk_len, dk = m.groups()
        g.kat(f"RFC 7914 PBKDF2-SHA256 c={c}",
              f"Crypto.pbkdf2(HashAlgorithm.Sha256, {lit(p.encode().hex())}, {lit(s.encode().hex())}, {c}, {dk_len}).data",
              re.sub(r"\s", "", dk))
    for m in re.finditer(r'scrypt \(P="([^"]*)", S="([^"]*)",\s+N=(\d+), r=(\d+), p=(\d+), dk[lL]en=(\d+)\) =\n((?:\s+(?:[0-9a-f]{2} ?)+\n)+)', t):
        p, s, n, r, par, dk_len, dk = m.groups()
        if int(n) > 16384:
            continue  # N = 2^20 needs 1 GiB and seconds of CPU
        log_n = int(n).bit_length() - 1
        g.kat(f"RFC 7914 scrypt N={n} r={r} p={par}",
              f"Crypto.scrypt({lit(p.encode().hex())}, {lit(s.encode().hex())}, {log_n}, {r}, {par}, {dk_len}).data",
              re.sub(r"\s", "", dk))
    return g


def gen_mac_kdf():
    g = Group("streaming HMAC")
    # RFC 4231 case 2 through Hasher.hmac, in two pieces, twice (the key is kept).
    want = "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"
    g.raw('var mac = Hasher.hmac(HashAlgorithm.Sha256, "Jefe")')
    g.raw('mac.update("what do ya want ")')
    g.raw('mac.update("for nothing?")')
    g.raw(f'ok += kat("Hasher.hmac RFC 4231 case 2", mac.finish(), "{want}")')
    g.raw("total += 1")
    g.raw('mac.update("what do ya want for nothing?")')
    g.raw(f'ok += kat("Hasher.hmac reused after finish", mac.finish(), "{want}")')
    g.raw("total += 1")
    write("crypto_mac_kdf_kat", "HMAC, HKDF, PBKDF2 and scrypt known-answer tests.",
          "RFC 2202, RFC 4231, RFC 5869, RFC 6070 and RFC 7914",
          [rfc2202(), rfc4231(), g, rfc5869(), rfc6070(), rfc7914()])


# ── AEAD ─────────────────────────────────────────────────────────────────

def hexdump(block, label):
    """Bytes of the RFC 8439 hexdump that follows `label`."""
    i = block.index(label)
    out = []
    for line in block[i + len(label):].splitlines()[1:]:
        m = re.match(r"^\s+\d{3}  ((?:[0-9a-f]{2} )*[0-9a-f]{2})", line)
        if m:
            out.append(m.group(1).replace(" ", ""))
        elif out and line.strip():
            break
    return "".join(out)


def gen_aead():
    t = text("rfc8439.txt")
    groups = []
    g = Group("ChaCha20-Poly1305 RFC 8439")
    start = t.rindex("2.8.2.  Example and Test Vector for AEAD_CHACHA20_POLY1305")
    s = t[start:t.index("3.  Implementation Advice", start)]
    pt = hexdump(s, "Plaintext:")
    aad = hexdump(s, "AAD:")
    key = hexdump(s, "Key:")
    iv = hexdump(s, "IV:")
    fixed = hexdump(s, "32-bit fixed-common part:")
    ct = hexdump(s, "Ciphertext:")
    tag = re.search(r"Tag:\s*\n?\s*((?:[0-9a-f]{2}:?)+)", s[s.index("Ciphertext:"):]).group(1).replace(":", "")
    nonce = fixed + iv
    g.kat("RFC 8439 2.8.2 seal",
          f"Crypto.seal(AeadAlgorithm.ChaCha20Poly1305, {lit(key)}, {lit(nonce)}, {lit(pt)}, {lit(aad)}).data",
          ct + tag)
    g.kat("RFC 8439 2.8.2 open",
          f"Crypto.open(AeadAlgorithm.ChaCha20Poly1305, {lit(key)}, {lit(nonce)}, {lit(ct + tag)}, {lit(aad)}).data",
          pt)
    start = t.rindex("A.5.  ChaCha20-Poly1305 AEAD Decryption")
    s = t[start:t.index("Appendix B.", start)]
    key = hexdump(s, "The ChaCha20 Key")
    ct = hexdump(s, "Ciphertext:")
    nonce = hexdump(s, "The nonce:")
    aad = hexdump(s, "The AAD:")
    tag = hexdump(s, "Received Tag:")
    pt = hexdump(s, "Plaintext::")
    g.kat("RFC 8439 A.5 open",
          f"Crypto.open(AeadAlgorithm.ChaCha20Poly1305, {lit(key)}, {lit(nonce)}, {lit(ct + tag)}, {lit(aad)}).data",
          pt)
    bad_tag = tag[:-2] + ("00" if tag[-2:] != "00" else "01")
    g.check("RFC 8439 A.5 with a corrupted tag is an authentication error",
            f"Crypto.open(AeadAlgorithm.ChaCha20Poly1305, {lit(key)}, {lit(nonce)}, {lit(ct + bad_tag)}, {lit(aad)}).error == 9004")
    groups.append(g)

    g = Group("AES-256-GCM NIST CAVP encrypt")
    seen = {}
    for r in rsp_records("gcmEncryptExtIV256.rsp"):
        hdr = r.get("_hdr", {})
        if hdr.get("IVlen") != 96 or hdr.get("Taglen") != 128 or "Key" not in r:
            continue
        sect = (hdr["PTlen"], hdr["AADlen"])
        if seen.get(sect, 0) >= 2:
            continue
        seen[sect] = seen.get(sect, 0) + 1
        label = f"GCM PTlen={hdr['PTlen']} AADlen={hdr['AADlen']} Count={r['Count']}"
        g.kat(label + " seal",
              f"Crypto.seal(AeadAlgorithm.Aes256Gcm, {lit(r['Key'])}, {lit(r['IV'])}, {lit(r['PT'])}, {lit(r['AAD'])}).data",
              r["CT"] + r["Tag"])
        g.kat(label + " open",
              f"Crypto.open(AeadAlgorithm.Aes256Gcm, {lit(r['Key'])}, {lit(r['IV'])}, {lit(r['CT'] + r['Tag'])}, {lit(r['AAD'])}).data",
              r["PT"])
    groups.append(g)

    g = Group("AES-256-GCM NIST CAVP decrypt")
    seen = {}
    for r in rsp_records("gcmDecrypt256.rsp"):
        hdr = r.get("_hdr", {})
        if hdr.get("IVlen") != 96 or hdr.get("Taglen") != 128 or "Key" not in r:
            continue
        sect = (hdr["PTlen"], hdr["AADlen"], "FAIL" in r)
        if seen.get(sect, 0) >= 1:
            continue
        seen[sect] = 1
        label = f"GCM decrypt PTlen={hdr['PTlen']} AADlen={hdr['AADlen']} Count={r['Count']}"
        call = f"Crypto.open(AeadAlgorithm.Aes256Gcm, {lit(r['Key'])}, {lit(r['IV'])}, {lit(r['CT'] + r['Tag'])}, {lit(r['AAD'])})"
        if "FAIL" in r:
            g.check(label + " FAIL", f"{call}.error == 9004")
        else:
            g.kat(label, call + ".data", r["PT"])
    groups.append(g)
    write("crypto_aead_kat", "Authenticated encryption known-answer tests.",
          "RFC 8439 and NIST CAVP gcmEncryptExtIV256 / gcmDecrypt256", groups)


# ── Encoding ─────────────────────────────────────────────────────────────

def gen_encoding():
    t = text("rfc4648.txt")
    g = Group("RFC 4648 section 10")
    for m in re.finditer(r'BASE64\("([^"]*)"\) = "([^"]*)"', t):
        data, enc = m.groups()
        g.check(f'BASE64 {data or "empty"} encode', f'Base64.encode("{data}") == "{enc}"')
        g.check(f'BASE64 {data or "empty"} decode', f'Base64.decode("{enc}").data == "{data}" and Base64.decode("{enc}").error == 0')
        url = enc.rstrip("=")
        g.check(f'base64url {data or "empty"} encode', f'Base64.url_encode("{data}") == "{url}"')
        g.check(f'base64url {data or "empty"} decode', f'Base64.url_decode("{url}").data == "{data}" and Base64.url_decode("{enc}").data == "{data}"')
    for m in re.finditer(r'BASE16\("([^"]*)"\) = "([^"]*)"', t):
        data, enc = m.groups()
        g.check(f'BASE16 {data or "empty"} encode', f'Hex.encode("{data}") == "{enc.lower()}"')
