#!/usr/bin/env python3
"""Writes src/runtime/iron_casemap.h: the simple (one character to one
character) upper and lower case mappings of Unicode, from Python's
unicodedata, as runs {first, last, delta, step}: every code point
first, first + step, ... last maps to itself plus delta. Characters whose
mapping is several characters (German sharp s to SS, ...) keep their case,
as do characters without one.

    scripts/gen_casemap.py > src/runtime/iron_casemap.h
"""
import sys
import unicodedata


def runs(f):
    pairs = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        m = f(chr(cp))
        if len(m) == 1 and ord(m) != cp:
            pairs.append((cp, ord(m) - cp))
    out = []
    i = 0
    while i < len(pairs):
        cp, d = pairs[i]
        best = (1, 1)
        for step in (1, 2):
            n = 1
            while (i + n < len(pairs) and pairs[i + n][0] == cp + n * step and pairs[i + n][1] == d):
                n += 1
            if n > best[0]:
                best = (n, step)
        n, step = best
        out.append((cp, cp + (n - 1) * step, d, step))
        i += n
    return out


def emit(name, rs):
    print(f'static const IronCaseRun {name}[{len(rs)}] = {{')
    for a, b, d, s in rs:
        print(f'    {{0x{a:X}, 0x{b:X}, {d}, {s}}},')
    print('};')


print('/* iron_casemap.h: simple Unicode case mappings for String.upper / lower.')
print(f' * Generated by scripts/gen_casemap.py from Unicode {unicodedata.unidata_version}; do not edit. */')
print('#ifndef IRON_CASEMAP_H\n#define IRON_CASEMAP_H\n')
print('typedef struct { uint32_t first, last; int32_t delta; uint8_t step; } IronCaseRun;\n')
emit('iron_case_upper', runs(str.upper))
print()
emit('iron_case_lower', runs(str.lower))
print('\n#endif')
